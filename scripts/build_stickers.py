import sys, os, re, json
from PIL import Image
src, out_assets, out_dart = sys.argv[1], sys.argv[2], sys.argv[3]
PACKS = [
  ('bunny', 'Bunny', ['1_products/emotes_bunny_1/1080']),
  ('tabby', 'Tabby', ['1_products/emotes_tabby/1080']),
  ('chonk', 'Chonk', ['1_products/emotes_cat_fat/pngs']),
  ('bonk', 'Bonk', ['1_products/emotes_rabbit_bonk/png']),
  ('mushroom', 'Mushroom', ['1_products/_unsold/stickers1-mushroom/upscale']),
  ('fries', 'Fries', ['1_products/twit ch - badge Fries']),
  ('fall', 'Fall', ['3_etsy/calendar1-fall/stickers']),
  ('categg', 'Cat egg', ['3_etsy/cat egg']),
  ('witchnotes', 'Witch notes', ['1_products/_unsold/majo- planner/majo-note-pad']),
  ('numbers', 'Numbers', ['1_products/_unsold/majo- planner/numbers']),
  ('witch', 'Witch', ['1_products/_unsold/majo- planner/everyday']),
  ('planner', 'Planner', ['1_products/_unsold/digital planner pack']),
  ('friends', 'Friends', ['3_etsy/chars', '3_etsy/imps', '3_etsy/Japan']),
]
nat = lambda s: [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', s)]
catalog, skipped, total = [], [], 0
for pid, name, dirs in PACKS:
    files = [os.path.join(d, f) for d in dirs for f in sorted(os.listdir(os.path.join(src, d)), key=nat) if f.lower().endswith('.png')]
    os.makedirs(os.path.join(out_assets, pid), exist_ok=True)
    items = []
    for rel in files:
        im = Image.open(os.path.join(src, rel)).convert('RGBA')
        a = im.getchannel('A')
        opaque = sum(1 for v in a.getdata() if v > 200) / (im.width * im.height)
        if opaque > .9:
            skipped.append(rel); continue
        box = a.point(lambda v: 255 if v > 8 else 0).getbbox()
        if not box:
            skipped.append(rel); continue
        im = im.crop(box)
        k = min(1, 400 / max(im.size))
        if k < 1:
            im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
        n = f'{len(items) + 1:02d}'
        im.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(os.path.join(out_assets, pid, n + '.png'), optimize=True)
        items.append((n, round(im.width / im.height, 3)))
    catalog.append((pid, name, items)); total += len(items)
with open(out_dart, 'w') as f:
    f.write('// Generated by scripts/build_stickers.py from Al\'s emote and sticker art.\n// Do not edit by hand.\n\n')
    f.write('/// Sticker packs: id, display name, and each sticker\'s file stem and width/height aspect.\n')
    f.write('const stickerPacks = <(String, String, List<(String, double)>)>[\n')
    for pid, name, items in catalog:
        f.write(f"  ('{pid}', '{name}', [\n")
        for i in range(0, len(items), 6):
            f.write('    ' + ' '.join(f"('{n}', {a})," for n, a in items[i:i+6]) + '\n')
        f.write('  ]),\n')
    f.write('];\n')
print(total, 'stickers;', 'skipped', len(skipped), ':', skipped)
for pid, name, items in catalog: print(f'  {name}: {len(items)}')
